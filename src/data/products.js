/**
 * Related products: same category first, then anything else, excluding the
 * product itself. Falls back to bestsellers for thin categories.
 */
export function getRelatedProducts(product, limit = 8) {
  if (!product) return [];

  const pool = PRODUCTS.filter((p) => p.id !== product.id);
  const sameCategory = pool.filter((p) => p.category === product.category);
  const others = pool.filter((p) => p.category !== product.category);

  const picks = [...sameCategory, ...others].slice(0, limit);

  return picks.length ? picks : BESTSELLERS.slice(0, limit);
}

