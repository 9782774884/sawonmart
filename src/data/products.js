/**
 * Look up a single product by id. Returns undefined when not found.
 *
 * Declared before the rails below because `SHUKRAWAT_PRODUCTS` calls it while
 * the module is still initialising — a `const` arrow function is not hoisted,
 * so referencing it earlier here would throw a TDZ error.
 */
