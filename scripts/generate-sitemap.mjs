/**
 * Generates public/sitemap.xml from the product catalogue.
 *
 * Why generate it instead of hand-writing it:
 *
 *   - robots.txt advertises this URL, so a missing sitemap is a dead link that
 *     search engines are told to expect. An earlier build referenced a sitemap
 *     that did not exist; the SPA rewrite then served index.html with a 200, so
 *     the "sitemap" looked like HTML to a crawler.
 *   - A hand-maintained list goes stale the moment a product is added. Reading
 *     the same module the storefront renders guarantees the two cannot drift.
 *
 * Run by `npm run build` (via prebuild). Committed output is refreshed too, so
 * the file is correct in a fresh clone before anyone builds.
 */

import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

import { PRODUCTS } from '../src/data/products.js';

/** This file lives in <repo>/scripts, so the repo root is one level up. */
const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const OUT = join(ROOT, 'public', 'sitemap.xml');

/**
 * Single source of truth for the public origin.
 *
 * Mirrors SITE.origin in src/utils/constants.js. A plain .js file cannot be
 * imported here without Vite's transform, so the value is duplicated — but the
 * check below fails the build if the two ever disagree.
 */
const ORIGIN = 'https://www.sawonstore.in';

/** The declared homepage origin in index.html, used for the consistency check. */
const INDEX_ORIGIN = /<link rel="canonical" href="(https?:\/\/[^/"]+)/.exec(
  await readFile(join(ROOT, 'index.html'), 'utf8')
)?.[1];

if (INDEX_ORIGIN && INDEX_ORIGIN !== ORIGIN) {
  throw new Error(
    `Origin mismatch:\n` +
      `  scripts/generate-sitemap.mjs uses ${ORIGIN}\n` +
      `  index.html canonical uses ${INDEX_ORIGIN}\n` +
      `Update both, otherwise canonical tags and the sitemap disagree.`
  );
}

/** RFC 3339 date, which is what sitemaps expect (YYYY-MM-DD is also allowed). */
const today = () => new Date().toISOString().slice(0, 10);

/** XML text nodes must escape these five characters. */
const esc = (value) =>
  String(value)
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, '&apos;');

const url = (loc, { priority = '0.7', changefreq = 'weekly', lastmod = today() } = {}) =>
  [
    '  <url>',
    `    <loc>${esc(`${ORIGIN}${loc}`)}</loc>`,
    `    <lastmod>${lastmod}</lastmod>`,
    `    <changefreq>${changefreq}</changefreq>`,
    `    <priority>${priority}</priority>`,
    '  </url>',
  ].join('\n');

const urls = [
  url('/', { priority: '1.0', changefreq: 'daily' }),

  ...PRODUCTS.map((p) =>
    url(`/product/${p.id}`, { priority: '0.8', changefreq: 'weekly' })
  ),
];

const xml = [
  '<?xml version="1.0" encoding="UTF-8"?>',
  '<!-- Generated by scripts/generate-sitemap.mjs — do not edit by hand. -->',
  '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">',
  ...urls,
  '</urlset>',
  '',
].join('\n');

await writeFile(OUT, xml, 'utf8');

console.log(
  `sitemap.xml: ${urls.length} URLs (1 homepage + ${PRODUCTS.length} products) -> public/sitemap.xml`
);